// Package bootstrap 提供环境侧"在线一键注册"能力：
// 环境上只需运行一条 curl | bash 命令，即可完成 agent 下载、安装与注册。
//   curl -sSL "http://gw:8080/bootstrap/install.sh?token=<令牌>&name=nic-01" | bash
// 无需手动下载二进制；二进制由网关自托管分发（--agent-bindir 目录）。
package bootstrap

import (
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
)

// Handler bootstrap HTTP 处理器。
type Handler struct {
	binDir string // 存放各平台 agent 二进制的目录，文件名: envpilot-agent-<goos>-<goarch>[.exe]
}

// New 创建 Handler。
func New(binDir string) *Handler {
	return &Handler{binDir: binDir}
}

// ServeHTTP 路由 /bootstrap/install.sh 与 /bootstrap/agent。
func (h *Handler) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	switch {
	case r.URL.Path == "/bootstrap/install.sh":
		h.serveInstallScript(w, r)
	case r.URL.Path == "/bootstrap/agent":
		h.serveAgentBinary(w, r)
	default:
		http.NotFound(w, r)
	}
}

// serveAgentBinary 下发对应平台的 agent 二进制。
// GET /bootstrap/agent?goos=linux&goarch=amd64
func (h *Handler) serveAgentBinary(w http.ResponseWriter, r *http.Request) {
	goos := r.URL.Query().Get("goos")
	goarch := r.URL.Query().Get("goarch")

	// 白名单校验，防止路径穿越
	allowedOS := map[string]bool{"linux": true, "windows": true, "darwin": true}
	allowedArch := map[string]bool{"amd64": true, "arm64": true, "386": true, "arm": true}
	if !allowedOS[goos] || !allowedArch[goarch] {
		http.Error(w, "unsupported goos/goarch", http.StatusBadRequest)
		return
	}

	name := "envpilot-agent-" + goos + "-" + goarch
	if goos == "windows" {
		name += ".exe"
	}
	f, err := os.Open(filepath.Join(h.binDir, name))
	if err != nil {
		http.Error(w, fmt.Sprintf("agent binary not found on gateway (put %s into --agent-bindir): %v", name, err), http.StatusNotFound)
		return
	}
	defer f.Close()

	w.Header().Set("Content-Type", "application/octet-stream")
	w.Header().Set("Content-Disposition", `attachment; filename="envpilot-agent"`)
	_, _ = io.Copy(w, f)
}

// serveInstallScript 按请求参数动态生成 POSIX sh 安装脚本。
// GET /bootstrap/install.sh?token=<必填>&name=&type=&tags=&env=
// env 格式: K1=V1,K2=V2（如 DOCKER_HOST=tcp://10.0.0.5:2375），将注入 agent 进程环境。
func (h *Handler) serveInstallScript(w http.ResponseWriter, r *http.Request) {
	q := r.URL.Query()
	token := q.Get("token")
	if token == "" {
		http.Error(w, "token query parameter is required", http.StatusBadRequest)
		return
	}

	// 网关地址：优先取请求方看到的 Host（穿透反代也正确），允许 ?gw= 覆盖
	scheme := "http"
	if r.TLS != nil {
		scheme = "https"
	}
	gateway := scheme + "://" + r.Host
	if gw := q.Get("gw"); gw != "" {
		gateway = strings.TrimRight(gw, "/")
	}

	script := fmt.Sprintf(installScriptTemplate,
		shQuote(gateway),
		shQuote(token),
		shQuote(q.Get("name")),
		shQuote(q.Get("type")),
		shQuote(q.Get("tags")),
		shQuote(q.Get("env")),
	)

	w.Header().Set("Content-Type", "text/x-shellscript; charset=utf-8")
	_, _ = w.Write([]byte(script))
}

// installScriptTemplate 是 POSIX sh 安装脚本模板（顺序对应上方 Sprintf 参数）。
// 行为：探测架构 → 从网关下载 agent → root+systemd 则安装为服务，否则 nohup 后台运行。
const installScriptTemplate = `#!/bin/sh
# EnvPilot agent online installer (generated by envpilot-gateway)
# 用法: curl -sSL "http://<gw>:8080/bootstrap/install.sh?token=<令牌>" | bash
set -eu

GATEWAY=%s
TOKEN=%s
NAME=%s
TYPE=%s
TAGS=%s
ENVVARS=%s

# 前台运行模式（调试用）: FOREGROUND=1 curl ... | bash
FOREGROUND="${FOREGROUND:-0}"

# 注入自定义环境变量（格式 K1=V1,K2=V2，如 DOCKER_HOST=tcp://10.0.0.5:2375）
if [ -n "$ENVVARS" ]; then
  OLDIFS=$IFS
  IFS=','
  for kv in $ENVVARS; do
    k="${kv%%=*}"
    v="${kv#*=}"
    if [ -n "$k" ] && [ "$k" != "$kv" ]; then
      export "$k=$v"
      echo "==> env: $k=<set>"
    fi
  done
  IFS=$OLDIFS
fi

case "$(uname -m)" in
  x86_64)  ARCH=amd64 ;;
  aarch64|arm64) ARCH=arm64 ;;
  *) echo "unsupported architecture: $(uname -m)" >&2; exit 1 ;;
esac
if [ "$(uname -s)" != "Linux" ]; then
  echo "this installer supports Linux only (uname: $(uname -s))" >&2; exit 1
fi

# 二进制安装位置：root 装系统目录，非 root 装 ~/.local/bin
if [ "$(id -u)" = "0" ]; then
  BIN=/usr/local/bin/envpilot-agent
else
  BIN="$HOME/.local/bin/envpilot-agent"
  mkdir -p "$(dirname "$BIN")"
fi

echo "==> downloading envpilot-agent (linux/$ARCH) from gateway ..."
if ! curl -fsSL "$GATEWAY/bootstrap/agent?goos=linux&goarch=$ARCH" -o "$BIN"; then
  echo "download failed: gateway has no agent binary for linux/$ARCH" >&2
  echo "hint: on the gateway host, run:" >&2
  echo "  GOOS=linux GOARCH=$ARCH go build -o <agent-bindir>/envpilot-agent-linux-$ARCH ./cmd/agent" >&2
  exit 1
fi
chmod +x "$BIN"

start_agent() {
  set -- "$BIN" --gateway "$GATEWAY/ws" --token "$TOKEN"
  [ -n "$NAME" ] && set -- "$@" --name "$NAME"
  [ -n "$TYPE" ] && set -- "$@" --type "$TYPE"
  [ -n "$TAGS" ] && set -- "$@" --tags "$TAGS"
  # exec 必须作用于二进制而非函数名（exec 函数名并非所有 sh 实现都支持）
  exec "$@"
}

if [ "$FOREGROUND" = "1" ]; then
  echo "==> starting envpilot-agent in foreground"
  start_agent
fi

# root + systemd 环境下安装为系统服务（开机自启）
if [ "$(id -u)" = "0" ] && command -v systemctl >/dev/null 2>&1; then
  echo "==> installing systemd service"
  ARGS="--gateway $GATEWAY/ws --token $TOKEN"
  [ -n "$NAME" ] && ARGS="$ARGS --name $NAME"
  [ -n "$TYPE" ] && ARGS="$ARGS --type $TYPE"
  [ -n "$TAGS" ] && ARGS="$ARGS --tags $TAGS"
  # systemd 不继承当前 shell 环境，需要显式 Environment= 行
  ENVLINES=""
  if [ -n "$ENVVARS" ]; then
    OLDIFS=$IFS
    IFS=','
    for kv in $ENVVARS; do
      k="${kv%%=*}"
      v="${kv#*=}"
      if [ -n "$k" ] && [ "$k" != "$kv" ]; then
        ENVLINES="${ENVLINES}Environment=\"$k=$v\"
"
      fi
    done
    IFS=$OLDIFS
  fi
  cat > /etc/systemd/system/envpilot-agent.service <<EOF
[Unit]
Description=EnvPilot environment agent
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=$BIN $ARGS
${ENVLINES}Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable --now envpilot-agent
  echo "==> installed: systemctl status envpilot-agent"
  echo "==> registered to gateway: $GATEWAY (name: ${NAME:-<hostname>})"
  exit 0
fi

# 无 systemd（容器等）：nohup 后台运行
echo "==> starting envpilot-agent in background (no systemd)"
LOG=/tmp/envpilot-agent.log
nohup start_agent >"$LOG" 2>&1 &
echo "==> agent started (pid $!, log: $LOG)"
echo "==> registered to gateway: $GATEWAY (name: ${NAME:-<hostname>})"
`

// shQuote 单引号包裹并转义，防注入。
func shQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
